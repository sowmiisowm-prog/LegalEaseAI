# PDF EXPORT
# ============================================================

def make_pdf(text, document_type="Legal Document"):

    text = clean_text(text)

    pdf = LegalPDF(
        brand_name="LegalEase",
        document_type=document_type
    )

    pdf.set_font(
        "Times",
        "",
        11
    )

    for raw_line in text.splitlines():

        line = raw_line.strip()

        # Empty line
        if not line:
            pdf.ln(4)
            continue

        # Numbered heading
        if re.match(r"^\d+[\.\)]\s+", line):

            if pdf.get_y() > pdf.h - 30:
                pdf.add_page()

            pdf.set_font(
                "Times",
                "B",
                11
            )

            _pdf_write_wrapped(
                pdf,
                line
            )

            pdf.set_font(
                "Times",
                "",
                11
            )

        # Uppercase heading
        elif line.upper() == line and len(line) < 100:

            if pdf.get_y() > pdf.h - 30:
                pdf.add_page()

            pdf.set_font(
                "Times",
                "B",
                11
            )

            _pdf_write_wrapped(
                pdf,
                line
            )

            pdf.set_font(
                "Times",
                "",
                11
            )

        # Normal paragraph
        else:

            _pdf_write_wrapped(
                pdf,
                line
            )

        pdf.ln(1)

    output = pdf.output()

    if isinstance(output, str):
        return output.encode("latin-1")

    return bytes(output)