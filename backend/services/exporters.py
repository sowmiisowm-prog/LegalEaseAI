# PDF
# ============================================================

class LegalPDF(FPDF):

    def __init__(
        self,
        brand_name="LegalEase",
        document_type="Legal Document",
    ):
        super().__init__()

        self.brand_name = brand_name
        self.document_type = document_type

        self.set_auto_page_break(
            auto=True,
            margin=20
        )

        self.set_margins(
            left=18,
            top=30,
            right=18
        )

        self.add_page()

    def header(self):

        # Logo
        if os.path.isfile(LOGO_PATH):
            try:
                self.image(
                    LOGO_PATH,
                    x=88,
                    y=8,
                    w=34
                )
            except Exception:
                pass

        # Document title
        self.set_y(32)

        self.set_font(
            "Times",
            "B",
            14
        )

        self.cell(
            0,
            7,
            self.document_type,
            align="C"
        )

        self.ln(16)

    def footer(self):

        self.set_y(-15)

        self.set_font(
            "Times",
            "",
            8
        )

        self.cell(
            0,
            5,
            f"{self.brand_name} - AI-assisted legal draft",
            align="C"
        )


# ============================================================
# SAFE MANUAL TEXT WRAPPING
# IMPORTANT: NO multi_cell() IS USED
# ============================================================

def _pdf_wrap_text(pdf, text, max_width):

    text = clean_text(text)

    if not text:
        return [""]

    words = text.split()

    lines = []
    current = ""

    for word in words:

        # Handle very long words
        if pdf.get_string_width(word) > max_width:

            if current:
                lines.append(current)
                current = ""

            piece = ""

            for char in word:

                test = piece + char

                if pdf.get_string_width(test) <= max_width:
                    piece = test

                else:
                    if piece:
                        lines.append(piece)

                    piece = char

            if piece:
                current = piece

            continue

        test = word if not current else current + " " + word

        if pdf.get_string_width(test) <= max_width:
            current = test

        else:
            if current:
                lines.append(current)

            current = word

    if current:
        lines.append(current)

    return lines or [""]


def _pdf_write_wrapped(pdf, text):

    text = clean_text(text)

    page_width = (
        pdf.w
        - pdf.l_margin
        - pdf.r_margin
    )

    line_height = 6

    lines = _pdf_wrap_text(
        pdf,
        text,
        page_width
    )

    for line in lines:

        if pdf.get_y() > pdf.h - 25:
            pdf.add_page()

        pdf.text(
            pdf.l_margin,
            pdf.get_y() + 4.5,
            line
        )

        pdf.ln(line_height)


