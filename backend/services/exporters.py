import os
import re
from io import BytesIO

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt
from fpdf import FPDF

from backend.utils.text import sanitize_text


PROJECT_ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
)

LOGO_PATH = os.path.join(
    PROJECT_ROOT,
    "backend",
    "assets",
    "logo.png",
)


def clean_text(text):
    if text is None:
        return ""

    text = sanitize_text(str(text))

    replacements = {
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2013": "-",
        "\u2014": "-",
        "\u2022": "-",
        "\u00a0": " ",
        "\t": "    ",
    }

    for old, new in replacements.items():
        text = text.replace(old, new)

    return text


# ============================================================
# TXT
# ============================================================

def make_txt(text, document_type="Legal Document"):
    text = clean_text(text)

    header = (
        f"{document_type}\n"
        f"{'=' * len(document_type)}\n\n"
    )

    footer = (
        "\n\n"
        "Generated by LegalEase\n"
        "AI-assisted legal draft. Review before signing or relying on this document.\n"
    )

    return (header + text + footer).encode("utf-8")


